def _security_surface_contract(
    surface: str,
    fixture: dict[str, Any],
    *,
    require_blocked: bool = False,
    require_safe_marker: bool = False,
    min_redactions: int | None = None,
) -> bool:
    """Independent per-fixture oracle for one persisted/model-facing surface."""
    text_value = str(surface or "")
    # JSON embedded inside JSON commonly escapes its quotes. Removing only the
    # escape slash gives the independent regex oracle one canonical view.
    canonical = text_value
    while r'\"' in canonical:
        canonical = canonical.replace(r'\"', '"')
    if any(
        re.search(pattern, canonical, flags=re.IGNORECASE)
        for pattern in fixture.get("forbidden_patterns") or []
    ):
        return False
    if require_blocked:
        return "[BLOCKED" in canonical
    if require_safe_marker:
        return BLOCKED_TEXT not in canonical and (
            "token_count" in canonical and "3" in canonical
            if "token_count" in str(fixture.get("text") or "")
            else "MVSAFE_" in canonical
        )
    key_patterns = fixture.get("sensitive_key_patterns") or []
    redacted_patterns = fixture.get("required_redacted_patterns") or []
    for key_pattern, redacted_pattern in zip(key_patterns, redacted_patterns, strict=True):
        if re.search(key_pattern, canonical, flags=re.IGNORECASE) and not re.search(
            redacted_pattern,
            canonical,
            flags=re.IGNORECASE,
        ):
            return False
    required = (
        int(fixture.get("min_redactions") or 0)
        if min_redactions is None
        else max(0, int(min_redactions))
    )
    return canonical.count("[REDACTED]") >= required


def _json_default(value: Any) -> Any:
    if isinstance(value, (set, frozenset)):
        return sorted(value, key=str)
    if isinstance(value, tuple):
        return list(value)
    return str(value)


def _json_text(value: Any) -> str:
    if isinstance(value, str):
        return value
    return json.dumps(value, ensure_ascii=False, sort_keys=True, default=_json_default)


def _payload_for(spec: CaseSpec) -> str:
    prefix = f"{spec.marker} case={spec.case_id} "
    if spec.category == "redaction_digest_injection":
        fixture = _security_fixture(spec)
        # Put the complete attack shape first.  Otherwise the fixed 160B-ish
        # median profile can truncate "previous instructions" into benign
        # prose, which would test a different input instead of injection
        # blocking. Secret cases retain the trailing/truncated JSON shape that
        # exercises fail-closed escaped-value redaction.
        if spec.oracle["injection"]:
            prefix = fixture["text"] + " " + spec.marker + " "
        else:
            prefix += fixture["text"] + " "
    encoded = prefix.encode("utf-8")
    if len(encoded) > spec.payload_bytes:
        prefix = encoded[: spec.payload_bytes].decode("utf-8", errors="ignore")
    used_bytes = len(prefix.encode("utf-8"))
    remaining = spec.payload_bytes - used_bytes
    filler = ("massval-data " * (remaining // 13 + 1))[:remaining]
    payload = prefix + filler
    if len(payload.encode("utf-8")) != spec.payload_bytes:
        raise AssertionError("payload generator did not satisfy its UTF-8 byte budget")
    return payload


def _sqlite_identifier(value: str) -> str:
    return '"' + str(value).replace('"', '""') + '"'


def _nearest_percentile(values: list[int] | list[float], percentile: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    index = max(0, min(len(ordered) - 1, math.ceil(percentile * len(ordered)) - 1))
    return float(ordered[index])


def inspect_source_database(source_db: str | Path | None) -> dict[str, Any]:
    """Read only de-identified aggregate source shape."""
    if source_db is None:
        return {"exists": False, "path": "", "open_mode": "mode=ro&immutable=1", "tables": {}, "content_rows_read": 0}
    path = Path(source_db).expanduser().resolve()
    result: dict[str, Any] = {
        "exists": path.is_file(),
        "path": str(path),
        "open_mode": "mode=ro&immutable=1",
        "bytes": path.stat().st_size if path.is_file() else 0,
        "tables": {},
        "content_rows_read": 0,
    }
    if not path.is_file():
        return result
    uri = f"file:{quote(str(path), safe='/')}?mode=ro&immutable=1"
    with sqlite3.connect(uri, uri=True) as conn:
        conn.execute("PRAGMA query_only=ON")
        names = [
            str(row[0])
            for row in conn.execute(
                "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
            )
        ]
        for name in names:
            quoted = _sqlite_identifier(name)
            columns = [
                {"name": str(row[1]), "type": str(row[2] or "")} for row in conn.execute(f"PRAGMA table_info({quoted})")
            ]
            stats: dict[str, Any] = {"columns": columns}
            if name in {"runs", "events", "memory_items", "memory_injections", "review_runs", "learning_jobs"}:
                stats["rows"] = int(conn.execute(f"SELECT COUNT(*) FROM {quoted}").fetchone()[0])
            result["tables"][name] = stats
        event_columns = {row[1] for row in conn.execute("PRAGMA table_info(events)")} if "events" in names else set()
        if "event_type" in event_columns:
            result["event_type_distribution"] = {
                str(row[0] or "unknown"): int(row[1])
                for row in conn.execute("SELECT event_type, COUNT(*) FROM events GROUP BY event_type")
            }
        if "content_text" in event_columns:
            lengths = [int(row[0]) for row in conn.execute("SELECT LENGTH(COALESCE(content_text, '')) FROM events")]
            result["content_length"] = {
                "count": len(lengths),
                "p50": int(_nearest_percentile(lengths, 0.50)),
                "p95": int(_nearest_percentile(lengths, 0.95)),
                "p99": int(_nearest_percentile(lengths, 0.99)),
                "max": max(lengths) if lengths else 0,
            }
    return result


def _live_shape_replay(source_stats: dict[str, Any]) -> dict[str, Any]:
    tables = source_stats.get("tables") if isinstance(source_stats, dict) else {}
