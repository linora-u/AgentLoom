def _benchmark_execution_orders(pair_count: int, seed: int) -> list[list[str]]:
    """Pre-register a balanced, seeded AB/BA execution schedule."""
    if pair_count < 2:
        raise ValueError("at least two benchmark pairs are required")
    orders = [["reference", "current"] for _ in range((pair_count + 1) // 2)]
    orders.extend([["current", "reference"] for _ in range(pair_count // 2)])
    random.Random(seed).shuffle(orders)
    return orders


def _fixed_point_payload_oracle(events: int, seed: int) -> list[int]:
    """Independently generate the exact UTF-8 byte plan expected in the DB.

    This deliberately duplicates the literal validation contract instead of
    importing the benchmark driver.  A broken driver therefore cannot define
    its own expected result.
    """
    events = int(events)
    if events < 1:
        raise ValueError("fixed-point payload oracle requires positive events")
    sizes: list[int] = []
    for rank in range(events):
        slot = 999 if events == 1 else (rank * 999) // (events - 1)
        if slot <= 499:
            size = 96 + (slot * 63) // 499
        elif slot <= 949:
            size = 160 + ((slot - 500) * 1_887) // 449
        elif slot <= 989:
            size = 2_048 + ((slot - 950) * 29_951) // 39
        elif slot <= 998:
            size = 32_000 + ((slot - 990) * 27_999) // 8
        else:
            size = 60_000
        sizes.append(size)
    random.Random(seed).shuffle(sizes)
    return sizes


def _fixed_point_payload_profile(sizes: list[int]) -> dict[str, Any]:
    if not sizes:
        raise ValueError("fixed-point payload profile requires samples")
    return {
        "algorithm": "seeded_quantile_slots_v1",
        "encoding": "utf-8",
        "target_decimal_bytes": dict(FIXED_POINT_PAYLOAD_TARGET_DECIMAL_BYTES),
        "actual_nearest_rank_bytes": {
            "p50": int(_nearest_percentile(sizes, 0.50)),
            "p95": int(_nearest_percentile(sizes, 0.95)),
            "p99": int(_nearest_percentile(sizes, 0.99)),
            "max": max(sizes),
        },
    }


def _performance_from_raw_samples(
    result: dict[str, Any],
    database: Path,
    *,
    measured_events: int,
    pair_seed: int,
    warmup_events: int,
) -> dict[str, float]:
    """Independently recompute metrics; never trust a driver aggregate."""
    samples = result.get("samples") or {}
    spec = (result.get("protocol") or {}).get("spec") or {}
    counts = result.get("counts") or {}
    append = samples.get("ledger_append")
    queries = samples.get("fts_query")
    expected_queries = min(1_000, measured_events)
    expected_counts = {
        "warmup_events": warmup_events,
        "measured_events": measured_events,
        "database_events": measured_events,
    }
    if counts != expected_counts:
        raise ValueError("raw count contract mismatch")
    if (
        int(spec.get("events") or 0) != measured_events
        or int(spec.get("warmup_events") if spec.get("warmup_events") is not None else -1)
        != warmup_events
        or int(spec.get("query_count") or 0) != expected_queries
        or int(spec.get("seed") if spec.get("seed") is not None else -1) != pair_seed
    ):
        raise ValueError("raw benchmark spec mismatch")
    expected_payload_sizes = _fixed_point_payload_oracle(measured_events, pair_seed)
    expected_payload_profile = _fixed_point_payload_profile(expected_payload_sizes)
    expected_payload_order_sha256 = hashlib.sha256(
        json.dumps(expected_payload_sizes, separators=(",", ":")).encode()
    ).hexdigest()
    if (
        spec.get("version") != FIXED_POINT_SPEC_VERSION
        or spec.get("payload_profile") != expected_payload_profile
        or spec.get("payload_order_sha256") != expected_payload_order_sha256
    ):
        raise ValueError("raw benchmark payload spec mismatch")
    if (
        measured_events == FIXED_POINT_BENCHMARK_EVENTS
        and expected_payload_profile["actual_nearest_rank_bytes"]
        != FIXED_POINT_RELEASE_ACTUAL_NEAREST_RANK_BYTES
    ):
        raise ValueError("release payload oracle diverged from literal profile")
    if not isinstance(append, list) or len(append) != measured_events:
        raise ValueError("raw append sample count mismatch")
    if not isinstance(queries, list) or len(queries) != expected_queries:
        raise ValueError("raw FTS sample count mismatch")

    def extract(rows: list[Any], *, expected_indices: list[int]) -> list[float]:
        indices: list[int] = []
        values: list[float] = []
        for row in rows:
            if not isinstance(row, dict) or type(row.get("index")) is not int:
                raise ValueError("raw sample index missing")
            raw_value = row.get("elapsed_ms")
            if isinstance(raw_value, bool) or not isinstance(raw_value, (int, float)):
                raise ValueError("raw latency sample missing")
            value = float(raw_value)
            if value <= 0 or not math.isfinite(value):
                raise ValueError("raw latency sample must be positive and finite")
            indices.append(int(row["index"]))
            values.append(value)
        if indices != expected_indices:
            raise ValueError("raw samples diverged from pre-registered order")
        if any(index < 0 or index >= measured_events for index in indices):
            raise ValueError("raw query index out of range")
        return values

    query_order = list(range(measured_events))
    random.Random(pair_seed).shuffle(query_order)
    query_order = query_order[:expected_queries]
    expected_query_hash = hashlib.sha256(
        json.dumps(query_order, separators=(",", ":")).encode()
    ).hexdigest()
    if spec.get("query_order_sha256") != expected_query_hash:
        raise ValueError("raw query order hash mismatch")
    append_values = extract(append, expected_indices=list(range(measured_events)))
    query_values = extract(queries, expected_indices=query_order)
    with sqlite3.connect(
        f"{database.resolve().as_uri()}?mode=ro&immutable=1",
        uri=True,
    ) as connection:
        payload_rows = connection.execute(
            """
            SELECT event_id, length(CAST(content_text AS BLOB))
            FROM events ORDER BY event_id
            """
        ).fetchall()
        integrity = str(connection.execute("PRAGMA integrity_check").fetchone()[0]).lower()
    actual_events = len(payload_rows)
    actual_event_ids = [str(row[0]) for row in payload_rows]
    actual_payload_sizes = [int(row[1]) for row in payload_rows]
    expected_event_ids = [
        f"fixed-point-event-{index:09d}" for index in range(measured_events)
    ]
    if actual_events != measured_events or integrity != "ok":
        raise ValueError("measured database count/integrity mismatch")
    if (
        actual_event_ids != expected_event_ids
        or actual_payload_sizes != expected_payload_sizes
        or _fixed_point_payload_profile(actual_payload_sizes)
        != expected_payload_profile
    ):
        raise ValueError("measured payload distribution/order mismatch")
    size_bytes = database.stat().st_size
    if size_bytes <= 0:
        raise ValueError("measured database is empty")
    return {
        "ledger_append_p95_ms": round(_nearest_percentile(append_values, 0.95), 6),
        "fts_query_p95_ms": round(_nearest_percentile(query_values, 0.95), 6),
        "bytes_per_event": round(size_bytes / measured_events, 6),
    }


