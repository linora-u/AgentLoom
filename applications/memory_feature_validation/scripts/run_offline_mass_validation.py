class _SessionEndGuard:
    def __init__(self, runtime: CampaignRuntime):
        self.runtime = runtime
        self.model_calls = 0
        self.detached_launches = 0
        self._kick: Callable[..., Any] | None = None
        self._model: Callable[..., Any] | None = None

    def install(self) -> None:
        import src.extensions.self_learning.distiller as distiller
        import src.extensions.self_learning.finalizer as finalizer

        self._kick = finalizer.kick_learning_worker
        self._model = distiller.distill_with_model

        def measured_safe_kick(db_path: str | Path | None = None) -> bool:
            """Exercise the real SQLite kick lease without spawning a worker."""
            started = time.perf_counter()
            queue = LearningJobQueue(db_path)
            kick_token = queue.claim_worker_kick_slot()
            exercised = bool(kick_token)
            if kick_token:
                exercised = queue.release_worker_kick_slot(kick_token)
            elapsed_ms = (time.perf_counter() - started) * 1000.0
            with self.runtime.detached_launch_lock:
                self.runtime.kick_call_timings_ms.append(elapsed_ms)
            return exercised

        finalizer.kick_learning_worker = measured_safe_kick

        def forbidden_model(*_args: Any, **_kwargs: Any) -> Any:
            self.model_calls += 1
            raise AssertionError("SessionEnd called the model synchronously")

        distiller.distill_with_model = forbidden_model

    def restore(self) -> None:
        import src.extensions.self_learning.distiller as distiller
        import src.extensions.self_learning.finalizer as finalizer

        if self._kick is not None:
            finalizer.kick_learning_worker = self._kick
        if self._model is not None:
            distiller.distill_with_model = self._model

    def run_detached_retention_proof(self) -> dict[str, Any]:
        """Launch one real model-free worker against an isolated explicit DB."""
        if self._kick is None:
            raise RuntimeError("SessionEnd guard was not installed")
        proof_root = self.runtime.queue.db_path.parent / "detached-retention-proof"
        proof_db = proof_root / "self_learning.db"
        proof_queue = LearningJobQueue(proof_db)
        proof_root_run_id = "offline-detached-retention-proof"
        proof_queue.enqueue(
            "retention",
            "offline-detached-retention-proof",
            proof_root_run_id,
            {
                "root_run_id": proof_root_run_id,
                "run_dir": str(proof_root / "learning" / "runs" / proof_root_run_id),
                "retention_date": "2026-07-11",
            },
        )
        started = time.perf_counter()
        launched = bool(self._kick(proof_queue.db_path))
        elapsed_ms = (time.perf_counter() - started) * 1000.0
        if launched:
            with self.runtime.detached_launch_lock:
                self.detached_launches += 1
                self.runtime.detached_launch_timings_ms.append(elapsed_ms)
        observed = _wait_for_detached_retention(proof_queue)
        return {
            **observed,
            "detached_proof_db_isolated": proof_queue.db_path != self.runtime.queue.db_path,
            "detached_proof_kick_used_explicit_db_path": launched,
        }


