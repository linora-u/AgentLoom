def _cell_has_prefix(value: Any, prefixes: tuple[str, ...]) -> bool:
    if value is None:
        return False
    if isinstance(value, bytes):
        return any(prefix.encode() in value for prefix in prefixes)
    text = str(value)
    return any(prefix in text for prefix in prefixes)


def scan_wal_shm_privacy(
    root: str | Path, prefixes: list[str] | tuple[str, ...] = FORBIDDEN_PREFIXES
) -> dict[str, Any]:
    """Scan forensic WAL/SHM bytes before a checkpoint can discard them.

    Open each file as soon as ``rglob`` yields it.  Collecting paths first and
    opening them only after a large artifact-tree walk creates an
    enumerate/open race: SQLite can unlink a clean WAL and the resulting
    ``OSError`` used to be misreported as a forbidden-byte match.
    """
    campaign_dir = Path(root).resolve()
    needles = tuple(
        (probe_index, str(prefix).encode())
        for probe_index, prefix in enumerate(prefixes)
        if str(prefix)
    )
    opened: list[tuple[Path, Any]] = []
    files_scanned = 0
    read_errors = 0
    disappeared_files = 0
    read_error_paths: list[str] = []
    for path in campaign_dir.rglob("*"):
        if not path.name.endswith(("-wal", "-shm")):
            continue
        files_scanned += 1
        try:
            opened.append((path, path.open("rb")))
        except FileNotFoundError:
            # This remains a hard audit failure, but it is not evidence that a
            # secret matched.  Keep the two signals independently auditable.
            read_errors += 1
            disappeared_files += 1
            read_error_paths.append(str(path.relative_to(campaign_dir)))
        except OSError:
            read_errors += 1
            read_error_paths.append(str(path.relative_to(campaign_dir)))

    hits = 0
    hit_details: dict[tuple[str, int], dict[str, Any]] = {}
    for path, handle in opened:
        try:
            overlap = max((len(needle) for _probe_index, needle in needles), default=1) - 1
            tail = b""
            bytes_read = 0
            while chunk := handle.read(4 * 1024 * 1024):
                data = tail + chunk
                for probe_index, needle in needles:
                    offset = 0
                    while (position := data.find(needle, offset)) >= 0:
                        # A match wholly inside the retained prefix was
                        # counted in the preceding chunk; a boundary-
                        # crossing match ends in new bytes and counts now.
                        if position + len(needle) > len(tail):
                            hits += 1
                            relative_path = str(path.relative_to(campaign_dir))
                            key = (relative_path, probe_index)
                            detail = hit_details.setdefault(
                                key,
                                {
                                    "path": relative_path,
                                    "probe_index": probe_index,
                                    "count": 0,
                                    "offsets": [],
                                },
                            )
                            detail["count"] += 1
                            if len(detail["offsets"]) < 10:
                                detail["offsets"].append(
                                    bytes_read - len(tail) + position
                                )
                        offset = position + max(1, len(needle))
                bytes_read += len(chunk)
                tail = data[-overlap:] if overlap else b""
        except OSError:
            read_errors += 1
            read_error_paths.append(str(path.relative_to(campaign_dir)))
        finally:
            handle.close()
    return {
        "passed": hits == 0 and read_errors == 0,
        "wal_shm_files_scanned": files_scanned,
        "wal_shm_forbidden_hits": hits,
        "wal_shm_forbidden_findings": sorted(
            hit_details.values(), key=lambda item: (item["path"], item["probe_index"])
        ),
        "wal_shm_read_errors": read_errors,
        "wal_shm_disappeared_files": disappeared_files,
        "wal_shm_read_error_paths": sorted(set(read_error_paths)),
    }


def scan_artifact_files_privacy(
    paths: list[Path] | tuple[Path, ...],
    prefixes: list[str] | tuple[str, ...] = FORBIDDEN_PREFIXES,
) -> dict[str, Any]:
    """Scan a bounded set of artifacts written after the full campaign scan."""
    needles = tuple(str(prefix).encode() for prefix in prefixes if str(prefix))
    hits = 0
    read_errors = 0
    read_error_paths: list[str] = []
    files_scanned = 0
    for raw_path in paths:
        path = Path(raw_path)
        files_scanned += 1
        try:
            data = (
                gzip.open(path, "rb").read()
                if path.suffix == ".gz"
                else path.read_bytes()
            )
        except (OSError, EOFError):
            read_errors += 1
            read_error_paths.append(str(path))
            continue
        hits += sum(data.count(needle) for needle in needles)
    return {
        "passed": hits == 0 and read_errors == 0,
        "artifact_forbidden_hits": hits,
        "artifact_files_scanned": files_scanned,
        "artifact_read_errors": read_errors,
        "artifact_read_error_paths": sorted(set(read_error_paths)),
    }


