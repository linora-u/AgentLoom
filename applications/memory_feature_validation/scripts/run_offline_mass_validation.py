def allocate_quotas(cases: int) -> dict[str, int]:
    cases = int(cases)
    if cases < 1:
        raise ValueError("cases must be a positive integer")
    total_weight = sum(CATEGORY_WEIGHTS.values())
    raw = {name: cases * weight / total_weight for name, weight in CATEGORY_WEIGHTS.items()}
    quotas = {name: int(value) for name, value in raw.items()}
    remaining = cases - sum(quotas.values())
    order = sorted(
        CATEGORY_WEIGHTS,
        key=lambda name: (-(raw[name] - quotas[name]), list(CATEGORY_WEIGHTS).index(name)),
    )
    for name in order[:remaining]:
        quotas[name] += 1
    return quotas


def payload_size_for_position(index: int, total: int) -> int:
    """Literal median/p95/p99/max profile from the validation contract."""
    index = int(index)
    total = int(total)
    if total < 1 or index < 0 or index >= total:
        raise ValueError("payload position must satisfy 0 <= index < total")
    slot = 999 if total == 1 else (index * 999) // (total - 1)
    if slot <= 499:
        return 96 + (slot * 63) // 499
    if slot <= 949:
        return 160 + ((slot - 500) * 1887) // 449
    if slot <= 989:
        return 2048 + ((slot - 950) * 29951) // 39
    if slot <= 998:
        return 32000 + ((slot - 990) * 27999) // 8
    return 60000


def _case_token(seed: int, category: str, category_index: int) -> str:
    return hashlib.sha256(f"{seed}:{category}:{category_index}".encode()).hexdigest()[:16]


def _oracle_for(category: str, index: int, seed: int) -> dict[str, Any]:
    """Generate expectations without importing or calling tested algorithms."""
    rng = random.Random(f"oracle:{seed}:{category}:{index}")
    if category == "ledger_fts_search_scroll":
        return {"variant": "unique_marker", "expected": True}
    if category == "redaction_digest_injection":
        variant = _SECURITY_VARIANTS[index % len(_SECURITY_VARIANTS)]
        return {
            "variant": variant,
            "positive": not variant.startswith("safe_"),
            "injection": "injection" in variant or "shell" in variant,
            "route": (
                "task",
                "final_answer",
                "event",
                "session_note",
                "existing_memory",
                "repeated_failure",
                "curator",
            )[index % 7],
            "expected": True,
        }
    if category == "exact_evidence_conflict":
        variant = _EVIDENCE_VARIANTS[index % len(_EVIDENCE_VARIANTS)]
        return {
            "variant": variant,
            "exact": variant in {"normalized_exact", "unicode_casefold_exact"},
            "same_run": variant == "same_run_exact",
            "expected": True,
        }
    if category == "revision_trust_feedback":
        return {
            "variant": _REVISION_VARIANTS[index % len(_REVISION_VARIANTS)],
            "signal": "old_outcome" if rng.randrange(2) == 0 else "new_feedback",
            "expected": True,
        }
    if category == "root_run_worker_concurrency":
        return {"variant": "hook_thread_owner_finalize", "expected": True}
    if category == "outbox_crash_lease_migration":
        return {"variant": _OUTBOX_VARIANTS[index % len(_OUTBOX_VARIANTS)], "expected": True}
    variant_slot = index % 10
    return {
        "variant": "ranking" if variant_slot < 6 else "snapshot" if variant_slot < 9 else "retention",
        "candidate_count": 12 + rng.randrange(13),
        "expected": True,
    }


def build_case_plan(cases: int, seed: int) -> list[CaseSpec]:
    quotas = allocate_quotas(cases)
    plan: list[CaseSpec] = []
    global_index = 0
    for category, quota in quotas.items():
        for category_index in range(quota):
            token = _case_token(seed, category, category_index)
            plan.append(
                CaseSpec(
                    global_index=global_index,
                    category_index=category_index,
                    category=category,
                    case_id=f"{category}-{category_index:06d}-{token[:8]}",
                    marker=f"mvtoken{token}",
                    payload_bytes=payload_size_for_position(global_index, cases),
                    oracle=_oracle_for(category, category_index, seed),
                )
            )
            global_index += 1
    return plan


