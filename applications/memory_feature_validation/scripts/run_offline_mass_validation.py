def scan_campaign_privacy(
    root: str | Path, prefixes: list[str] | tuple[str, ...] = FORBIDDEN_PREFIXES
) -> dict[str, Any]:
    """Scan every DB column (including FTS shadow tables) and every artifact."""
    campaign_dir = Path(root).resolve()
    needles = tuple(str(prefix) for prefix in prefixes if str(prefix))
    database_hits = 0
    fts_hits = 0
    tables_scanned = 0
    db_files = list(campaign_dir.rglob("*.db"))
    for db in db_files:
        try:
            uri = f"file:{quote(str(db), safe='/')}?mode=ro&immutable=1"
            with sqlite3.connect(uri, uri=True) as conn:
                tables = [str(row[0]) for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")]
                for table in tables:
                    columns = [str(row[1]) for row in conn.execute(f"PRAGMA table_info({_sqlite_identifier(table)})")]
                    if not columns:
                        continue
                    tables_scanned += 1
                    query = (
                        "SELECT "
                        + ",".join(_sqlite_identifier(column) for column in columns)
                        + " FROM "
                        + _sqlite_identifier(table)
                    )
                    cursor = conn.execute(query)
                    while True:
                        batch = cursor.fetchmany(500)
                        if not batch:
                            break
                        for row in batch:
                            for value in row:
                                if _cell_has_prefix(value, needles):
                                    database_hits += 1
                                    if table.startswith("events_fts"):
                                        fts_hits += 1
        except sqlite3.DatabaseError:
            database_hits += 1
    artifact_hits = 0
    wal_privacy = scan_wal_shm_privacy(campaign_dir, needles)
    wal_shm_files_scanned = int(wal_privacy["wal_shm_files_scanned"])
    wal_shm_hits = int(wal_privacy["wal_shm_forbidden_hits"])
    wal_shm_files = {
        path
        for path in campaign_dir.rglob("*")
        if path.is_file() and path.name.endswith(("-wal", "-shm"))
    }
    for path in campaign_dir.rglob("*"):
        if not path.is_file() or path in db_files or path in wal_shm_files:
            continue
        try:
            data = gzip.open(path, "rb").read() if path.suffix == ".gz" else path.read_bytes()
        except (OSError, EOFError):
            artifact_hits += 1
            continue
        artifact_hits += sum(data.count(prefix.encode()) for prefix in needles)
    return {
        "passed": (
            database_hits == 0
            and artifact_hits == 0
            and wal_shm_hits == 0
            and bool(wal_privacy["passed"])
        ),
        "database_forbidden_hits": database_hits,
        "fts_forbidden_hits": fts_hits,
        "artifact_forbidden_hits": artifact_hits,
        "database_tables_scanned": tables_scanned,
        "database_files_scanned": len(db_files),
        "wal_shm_files_scanned": wal_shm_files_scanned,
        "wal_shm_forbidden_hits": wal_shm_hits,
        "wal_shm_forbidden_findings": wal_privacy[
            "wal_shm_forbidden_findings"
        ],
        "wal_shm_read_errors": int(wal_privacy["wal_shm_read_errors"]),
        "wal_shm_disappeared_files": int(
            wal_privacy["wal_shm_disappeared_files"]
        ),
        "wal_shm_read_error_paths": wal_privacy["wal_shm_read_error_paths"],
        "forbidden_probe_count": len(needles),
    }


