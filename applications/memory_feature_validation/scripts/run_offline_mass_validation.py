class _DeterministicModelStub:
    """Provider-level stub; all production digest/proposal code remains live."""

    def __init__(self) -> None:
        self.calls: list[str] = []
        self.valid_contents: list[str] = []
        self.forged_contents: list[str] = []
        self.fail = False
        self.include_forged = False

    def completion(self, **kwargs: Any) -> dict[str, Any]:
        digest_text = str(kwargs["messages"][-1]["content"])
        self.calls.append(digest_text)
        if self.fail:
            raise RuntimeError("deterministic offline provider failure")
        payload = json.loads(digest_text)
        fragments = payload.get("fragments") if isinstance(payload, dict) else []
        valid_refs = [
            str(fragment["ref"])
            for fragment in fragments or []
            if isinstance(fragment, dict) and not fragment.get("blocked") and str(fragment.get("ref") or "")
        ]
        proposals: list[dict[str, Any]] = []
        if valid_refs:
            digest_id = hashlib.sha256(digest_text.encode()).hexdigest()[:20]
            content = f"Offline validated durable fact {digest_id}"
            self.valid_contents.append(content)
            proposals.append(
                {
                    "scope": "project",
                    "content": content,
                    "replaces": "",
                    "evidence_refs": [valid_refs[0]],
                }
            )
            if self.include_forged:
                forged = f"Offline forged fact {digest_id}"
                self.forged_contents.append(forged)
                proposals.append(
                    {
                        "scope": "project",
                        "content": forged,
                        "replaces": "",
                        "evidence_refs": ["forged:ref"],
                    }
                )
        return {"choices": [{"message": {"content": json.dumps({"proposals": proposals})}}]}


class _ProductionReviewGuard:
    def __init__(self, stub: _DeterministicModelStub):
        self.stub = stub
        self._memory_config: Callable[..., Any] | None = None
        self._get_model: Callable[..., Any] | None = None
        self._completion: Callable[..., Any] | None = None

    def install(self) -> None:
        import litellm

        import src.extensions.self_learning.reviewer as reviewer
        import src.lib.smolagents.models.model_manager as model_manager

        self._memory_config = reviewer.memory_config
        self._get_model = model_manager.get_model
        self._completion = litellm.completion
        reviewer.memory_config = lambda: {
            "distill_enabled": True,
            "distill_model": "summary",
            "auto_apply": "off",
        }
        model_manager.get_model = lambda *_args, **_kwargs: {"model": "offline-stub"}
        litellm.completion = self.stub.completion

    def restore(self) -> None:
        import litellm

        import src.extensions.self_learning.reviewer as reviewer
        import src.lib.smolagents.models.model_manager as model_manager

        if self._memory_config is not None:
            reviewer.memory_config = self._memory_config
        if self._get_model is not None:
            model_manager.get_model = self._get_model
        if self._completion is not None:
            litellm.completion = self._completion


def _job_artifact_count(run_dir: Path, job_id: int) -> tuple[int, int]:
    artifact_dir = run_dir / "learning_jobs"
    committed = sum(path.is_file() for path in (artifact_dir / f"{job_id}.json", artifact_dir / f"{job_id}.md"))
    temporary = len(list(artifact_dir.glob("*.tmp"))) if artifact_dir.exists() else 0
    return committed, temporary


def _production_crash_and_fallback_probes(
    queue: LearningJobQueue,
    stub: _DeterministicModelStub,
) -> dict[str, Any]:
    from src.extensions.self_learning.reviewer import (
        process_retention_job,
        process_session_review_job,
    )

    store = MemoryStore()
    ledger = SelfLearningLedger()
    base = datetime.now(UTC)

    # Crash after semantic DB effects but before job completion/artifact write.
    crash_run = "massval-production-crash-review"
    crash_dir = queue.db_path.parent / "production_probes" / crash_run
    store.add(
        "session",
        "The crash probe export endpoint uses cursor pagination",
        proposal=False,
        source="offline_validation",
        scope_id=crash_run,
    )
    crash_job = queue.enqueue(
        "session_review",
        crash_run,
        crash_run,
        {
            "root_run_id": crash_run,
            "application_id": "default",
            "run_dir": str(crash_dir),
        },
        now=base,
    )
    old_owner = "massval-crashed-production-worker"
    old_token = queue.acquire_worker_lease(old_owner, now=base, lease_seconds=1)
    claimed = queue.claim(old_owner, str(old_token), now=base, lease_seconds=1)
    if claimed is not None:
        claimed["_clock_now"] = base.isoformat()
    crash_call_start = len(stub.calls)
    stub.include_forged = True
    first_execution = process_session_review_job(claimed, queue=queue) if claimed else None
    # Deliberately omit complete() and after_commit(): process dies here.
    del first_execution
    recovery = LearningJobWorker(queue, owner="massval-recovery-production-worker")
    try:
        recovery_outcome = recovery.run_once(now=base + timedelta(seconds=2))
    finally:
        _release_worker(recovery)
    stub.include_forged = False
    crash_inputs = stub.calls[crash_call_start:]
    finished_crash = queue.get_job(int(crash_job["id"]))
    prepared = finished_crash.get("payload", {}).get("prepared_digest") or {}
    with ledger._connect() as conn:
        crash_audits = int(
            conn.execute(
                "SELECT COUNT(*) FROM review_runs WHERE learning_job_id = ?",
                (int(crash_job["id"]),),
            ).fetchone()[0]
        )
        valid_rows = int(
            conn.execute(
                "SELECT COUNT(*) FROM memory_items WHERE content = ?",
                (stub.valid_contents[-1],),
            ).fetchone()[0]
        )
        forged_rows = sum(
            int(conn.execute("SELECT COUNT(*) FROM memory_items WHERE content = ?", (content,)).fetchone()[0])
            for content in stub.forged_contents
        )
    crash_artifacts, crash_tmp = _job_artifact_count(crash_dir, int(crash_job["id"]))

    # Three real production attempts reuse one frozen digest; attempt three
    # takes deterministic session-note fallback and never templates failures.
    fallback_run = "massval-production-fallback-review"
    fallback_dir = queue.db_path.parent / "production_probes" / fallback_run
    fallback_note = "The fallback probe endpoint uses explicit cursor pagination"
    store.add(
        "session",
        fallback_note,
        proposal=False,
        source="offline_validation",
        scope_id=fallback_run,
    )
    repeated_failure = "temporary tool failure must not become durable memory"
    for index in range(2):
        ledger.append_event(
            CanonicalSessionEvent(
                event_id=f"fallback-error-{index}",
                run_id=fallback_run,
                root_run_id=fallback_run,
                event_type="tool_error",
                tool_name="offline_probe",
                content_text=repeated_failure,
                output_data={"error": repeated_failure},
                created_at=(base + timedelta(microseconds=index)).isoformat(),
            )
        )
    fallback_job = queue.enqueue(
        "session_review",
        fallback_run,
        fallback_run,
        {
            "root_run_id": fallback_run,
            "application_id": "default",
            "run_dir": str(fallback_dir),
        },
        now=base,
    )
    fallback_call_start = len(stub.calls)
    stub.fail = True
    fallback_worker = LearningJobWorker(queue, owner="massval-fallback-production-worker")
    try:
        fallback_outcomes = [
            fallback_worker.run_once(now=base),
            fallback_worker.run_once(now=base + timedelta(seconds=2)),
            fallback_worker.run_once(now=base + timedelta(seconds=12)),
        ]
    finally:
        _release_worker(fallback_worker)
        stub.fail = False
    fallback_inputs = stub.calls[fallback_call_start:]
    finished_fallback = queue.get_job(int(fallback_job["id"]))
    with ledger._connect() as conn:
        fallback_audits = int(
            conn.execute(
                "SELECT COUNT(*) FROM review_runs WHERE learning_job_id = ?",
                (int(fallback_job["id"]),),
            ).fetchone()[0]
        )
        fallback_note_rows = int(
            conn.execute(
                "SELECT COUNT(*) FROM memory_items WHERE content = ? AND status = 'pending'",
                (fallback_note,),
            ).fetchone()[0]
        )
        templated_failure_rows = int(
            conn.execute(
                "SELECT COUNT(*) FROM memory_items WHERE content LIKE ?",
                (f"%{repeated_failure}%",),
            ).fetchone()[0]
        )

    # Real retention handler: prune commits, process crashes before terminal
    # job state, then the reclaimed production handler completes idempotently.
    with ledger._connect() as conn:
        conn.execute("DELETE FROM maintenance WHERE key='last_auto_prune_at'")
    retention_run = "massval-production-retention-crash"
    retention_dir = queue.db_path.parent / "production_probes" / retention_run
    stale_note = store.add(
        "session",
        "stale retention probe note",
        proposal=False,
        source="offline_validation",
        scope_id=retention_run,
    )
    with ledger._connect() as conn:
        conn.execute(
            "UPDATE memory_items SET updated_at='2000-01-01T00:00:00+00:00' WHERE id=?",
            (int(stale_note["id"]),),
        )
    ledger.append_event(
        CanonicalSessionEvent(
            event_id="production-retention-old-event",
            run_id=retention_run,
            root_run_id=retention_run,
            event_type="tool_result",
            content_text="production retention old marker",
            created_at="2000-01-01T00:00:00+00:00",
        )
    )
    retention_job = queue.enqueue(
        "retention",
        "production-retention-crash",
        retention_run,
        {"root_run_id": retention_run, "run_dir": str(retention_dir)},
        now=base,
    )
    retention_owner = "massval-crashed-retention-worker"
    retention_token = queue.acquire_worker_lease(retention_owner, now=base, lease_seconds=1)
    retention_claim = queue.claim(retention_owner, str(retention_token), now=base, lease_seconds=1)
    if retention_claim is not None:
        retention_claim["_clock_now"] = base.isoformat()
    retention_execution = process_retention_job(retention_claim, queue=queue) if retention_claim else None
    del retention_execution
    retention_recovery = LearningJobWorker(queue, owner="massval-retention-recovery-worker")
    try:
        retention_outcome = retention_recovery.run_once(now=base + timedelta(seconds=2))
    finally:
        _release_worker(retention_recovery)
    finished_retention = queue.get_job(int(retention_job["id"]))
    retention_artifacts, retention_tmp = _job_artifact_count(retention_dir, int(retention_job["id"]))
    retention_state_gone = bool(
        not store.active_session_notes(retention_run)
        and not ledger.search_events("production retention old marker", scope="all")
    )

    # One real curator pass proves that its production evidence whitelist, not
    # merely DigestBuilder labels, rejects a forged reference.
    import litellm

    from src.extensions.self_learning.curator import curate_memory

    curator_scope = "massval-production-curator"
    curator_ids = [
        int(
            store.add(
                "application",
                content,
                proposal=False,
                source="offline_validation",
                scope_id=curator_scope,
            )["id"]
        )
        for content in (
            "Curator probe backups run nightly at 02:00",
            "Curator probe backup job runs every night",
            "Curator probe dashboards live under operations",
        )
    ]
    with ledger._connect() as conn:
        conn.execute(
            f"UPDATE memory_items SET updated_at='2000-01-01T00:00:00+00:00' "
            f"WHERE id IN ({','.join('?' for _ in curator_ids)})",
            curator_ids,
        )
    prior_completion = litellm.completion

    def curator_completion(**_kwargs: Any) -> dict[str, Any]:
        return {
            "choices": [
                {
                    "message": {
                        "content": json.dumps(
                            {
                                "proposals": [
                                    {
                                        "action": "replace",
                                        "target": str(curator_ids[0]),
                                        "content": "Curator probe backups run nightly",
                                        "reason": "consolidate",
                                        "evidence_refs": [f"memory:{curator_ids[0]}"],
                                    },
                                    {
                                        "action": "remove",
                                        "target": str(curator_ids[1]),
                                        "content": "",
                                        "reason": "forged",
                                        "evidence_refs": ["forged:ref"],
                                    },
                                ]
                            }
                        )
                    }
                }
            ]
        }

    litellm.completion = curator_completion
    try:
        curator_result = curate_memory(scope="app", scope_id=curator_scope, model_type="summary")
    finally:
        litellm.completion = prior_completion
    curator_validation_route = bool(
        len(curator_result.get("proposals") or []) == 1
        and (curator_result["proposals"][0]["target"] == str(curator_ids[0]))
        and any(
            entry.get("reason") == "unknown_or_blocked_evidence_ref" for entry in curator_result.get("skipped") or []
        )
    )

    return {
        "frozen_digest_reused": bool(
            # Attempt one freezes both digest and validated semantic plan before
            # applying effects. Recovery must resume that plan without a second
            # stochastic provider call.
            len(crash_inputs) == 1
            and prepared.get("sha256") == hashlib.sha256(crash_inputs[0].encode()).hexdigest()
            and bool(finished_crash.get("payload", {}).get("semantic_plan"))
        ),
        "proposal_evidence_filtered": bool(valid_rows == 1 and forged_rows == 0),
        "review_audit_idempotent": crash_audits == 1,
        "crash_recovery_succeeded": bool(
            recovery_outcome == "succeeded"
            and finished_crash["status"] == "succeeded"
            and int(finished_crash["attempts"]) == 2
            and crash_artifacts == 2
            and crash_tmp == 0
        ),
        "fallback_digest_reused": bool(len(fallback_inputs) == 3 and len(set(fallback_inputs)) == 1),
        "fallback_succeeded": bool(
            fallback_outcomes == ["retry", "retry", "succeeded"]
            and int(finished_fallback["attempts"]) == 3
            and finished_fallback["result"]["distill"]["distilled_by"] == "deterministic(fallback)"
            and fallback_audits == 1
            and fallback_note_rows == 1
            and templated_failure_rows == 0
        ),
        "retention_crash_recovered": bool(
            retention_outcome == "succeeded"
            and finished_retention["status"] == "succeeded"
            and int(finished_retention["attempts"]) == 2
            and retention_state_gone
            and retention_artifacts == 2
            and retention_tmp == 0
        ),
        "curator_validation_route": curator_validation_route,
    }


def _drain_session_jobs(queue: LearningJobQueue, max_jobs: int) -> dict[str, Any]:
    with queue.ledger._connect() as conn:
        initial_jobs = conn.execute("SELECT id, kind FROM learning_jobs ORDER BY id").fetchall()
    review_ids = [int(job["id"]) for job in initial_jobs if job["kind"] == "session_review"]
    retention_ids = [int(job["id"]) for job in initial_jobs if job["kind"] == "retention"]
    initial_max_id = max((int(job["id"]) for job in initial_jobs), default=0)
    stub = _DeterministicModelStub()
    guard = _ProductionReviewGuard(stub)
    guard.install()
    try:
        worker = LearningJobWorker(queue, owner="massval-production-session-drain")
        summary = worker.run_until_idle(max_jobs=max_jobs, wait_for_retries=False)
        probes = _production_crash_and_fallback_probes(queue, stub)
    finally:
        guard.restore()
    with queue.ledger._connect() as conn:
        initial_audits = {
            int(row["learning_job_id"]): int(row["count"])
            for row in conn.execute(
                "SELECT r.learning_job_id, COUNT(*) AS count "
                "FROM review_runs r JOIN learning_jobs j ON j.id = r.learning_job_id "
                "WHERE j.id <= ? AND j.kind = 'session_review' "
                "GROUP BY r.learning_job_id",
                (initial_max_id,),
            )
        }
        nonterminal_initial = int(
            conn.execute(
                "SELECT COUNT(*) FROM learning_jobs WHERE id <= ? AND status != 'succeeded'",
                (initial_max_id,),
            ).fetchone()[0]
        )
        forged_rows = int(
            conn.execute("SELECT COUNT(*) FROM memory_items WHERE content LIKE 'Offline forged fact %'").fetchone()[0]
        )
    initial_terminal = bool(initial_jobs and nonterminal_initial == 0)
    return {
        **summary,
        "session_review_checked": len(review_ids),
        "retention_checked": len(retention_ids),
        "provider_calls": len(stub.calls),
        "initial_jobs_terminal": initial_terminal,
        "normal_review_audits": bool(
            set(initial_audits) == set(review_ids) and all(count == 1 for count in initial_audits.values())
        ),
        "initial_review_audit_count": sum(initial_audits.values()),
        "initial_review_job_ids": review_ids,
        "forged_proposals_absent": forged_rows == 0,
        **probes,
    }


def _wait_for_detached_retention(queue: LearningJobQueue, *, timeout_seconds: float = 20.0) -> dict[str, Any]:
    """Wait for the isolated detached-worker retention proof to finish."""
    deadline = time.monotonic() + timeout_seconds
    observed: dict[str, Any] | None = None
    leases_released = False
    while time.monotonic() < deadline:
        retention = [job for job in queue.list_jobs(limit=1000) if job["kind"] == "retention"]
        if len(retention) == 1:
            observed = retention[0]
        with queue.ledger._connect() as conn:
            leases_released = not bool(
                conn.execute(
                    "SELECT 1 FROM maintenance WHERE key IN ('learning_worker_lease', 'learning_worker_kick_lease')"
                ).fetchone()
            )
        if observed and observed["status"] in {"succeeded", "dead"} and leases_released:
            break
        time.sleep(0.05)
    return {
        "detached_central_job_id": int(observed["id"]) if observed else 0,
        "detached_central_job_terminal": bool(
            observed
            and observed["status"] == "succeeded"
            and int(observed["attempts"]) >= 1
            and observed["finished_at"]
            and not observed["lease_owner"]
            and leases_released
        ),
        "detached_central_job_attempts": int(observed["attempts"]) if observed else 0,
        "detached_observed_before_in_process_drain": True,
    }


def _root_review_jobs_attributed(queue: LearningJobQueue, specs: list[CaseSpec]) -> bool:
    """Verify SessionEnd naturally enqueued one review for every root."""
    expected = {f"root-{spec.case_id}" for spec in specs}
    with queue.ledger._connect() as conn:
        jobs = conn.execute(
            "SELECT root_run_id, payload_json, status FROM learning_jobs "
            "WHERE kind = 'session_review' ORDER BY id"
        ).fetchall()
    return bool(
        {str(job["root_run_id"]) for job in jobs} == expected
        and len(jobs) == len(expected)
        and all(job["status"] == "pending" for job in jobs)
        and all(
            str(json.loads(job["payload_json"]).get("root_run_id") or "")
            == job["root_run_id"]
            for job in jobs
        )
    )


def _execute_plan(
    plan: list[CaseSpec],
    runtime: CampaignRuntime,
    workers: int,
) -> tuple[list[CaseResult], int, dict[str, Any]]:
    results: list[CaseResult] = []
    model_calls = 0
    production_jobs: dict[str, Any] = {}
    for category in CATEGORY_WEIGHTS:
        specs = [spec for spec in plan if spec.category == category]
        if not specs:
            continue
        category_workers = workers if category in {"ledger_fts_search_scroll", "root_run_worker_concurrency"} else 1
        guard = _SessionEndGuard(runtime) if category == "root_run_worker_concurrency" else None
        job_log_guard = _ExpectedJobLogGuard() if category == "outbox_crash_lease_migration" else None
        if guard:
            guard.install()
        if job_log_guard:
            job_log_guard.install()
        try:
            with ThreadPoolExecutor(
                max_workers=category_workers, thread_name_prefix=f"massval-{category[:12]}"
            ) as executor:
                results.extend(executor.map(lambda spec: _execute_case(spec, runtime), specs))
        finally:
            if guard:
                model_calls += guard.model_calls
                guard.restore()
            if job_log_guard:
                job_log_guard.restore()
        if category == "root_run_worker_concurrency":
            assert guard is not None
            detached = guard.run_detached_retention_proof()
            root_jobs_attributed = _root_review_jobs_attributed(runtime.queue, specs)
            production_jobs = _drain_session_jobs(runtime.queue, max_jobs=len(specs) + 10)
            production_jobs.update(detached)
            production_jobs["root_review_jobs_attributed"] = root_jobs_attributed
    results.sort(key=lambda item: item.global_index)
    return results, model_calls, production_jobs


def _security_forensic_support_set(specs: list[CaseSpec]) -> list[CaseSpec]:
    """Choose one deterministic probe for every independent security path."""
    selected: dict[tuple[Any, ...], CaseSpec] = {}
    for spec in specs:
        key = (
            str(spec.oracle.get("route") or ""),
            str(spec.oracle.get("variant") or ""),
            bool(spec.oracle.get("positive")),
            bool(spec.oracle.get("injection")),
        )
        selected.setdefault(key, spec)
    return list(selected.values())


def _run_security_wal_forensics(
    specs: list[CaseSpec],
    *,
    campaign_dir: Path,
    source_stats: dict[str, Any],
    events_per_run: int,
) -> dict[str, Any]:
    """Replay every security case in bounded one-shot WAL databases.

    The central 100k ledger exercises the production paths and is audited in
    its final DB/FTS/artifacts. These isolated replays add the stronger
    transient guarantee: one reader pins every WAL frame for a bounded chunk,
    the bytes are scanned, and that database is never reused after checkpoint.
    This avoids unsafe in-process WAL-index resets on macOS while preserving a
    replay of every independent route/fixture contract represented by the full
    20k central cohort. Random marker suffixes are not separate code paths.
    """
    source_case_count = len(specs)
    specs = _security_forensic_support_set(specs)
    root = campaign_dir / "wal_forensics"
    root.mkdir(parents=True, exist_ok=True)
    segments: list[dict[str, Any]] = []
    totals = {
        "database_forbidden_hits": 0,
        "fts_forbidden_hits": 0,
        "artifact_forbidden_hits": 0,
        "wal_shm_files_scanned": 0,
        "wal_shm_forbidden_hits": 0,
        "wal_shm_read_errors": 0,
        "wal_shm_disappeared_files": 0,
    }
    all_passed = True
    replayed_cases = 0
    for offset in range(0, len(specs), _WAL_FORENSIC_CHUNK_CASES):
        chunk = specs[offset : offset + _WAL_FORENSIC_CHUNK_CASES]
        segment_index = offset // _WAL_FORENSIC_CHUNK_CASES
        segment_dir = root / f"segment-{segment_index:03d}"
        segment_dir.mkdir()
        db_path = segment_dir / "self_learning.db"
        sink = SecurityArtifactSink(segment_dir / "security_surfaces.jsonl")
        nested = ThreadPoolExecutor(max_workers=2, thread_name_prefix="massval-forensic")
        keeper: sqlite3.Connection | None = None
        execution_completed = False
        with _campaign_environment(segment_dir):
            ledger = SelfLearningLedger(db_path)
            runtime = CampaignRuntime(
                ledger=ledger,
                memory_store=MemoryStore(db_path),
                queue=LearningJobQueue(db_path),
                nested_executor=nested,
                security_sink=sink,
                worker_artifacts=segment_dir / "worker_artifacts",
                events_per_run=events_per_run,
                source_stats=source_stats,
                kick_call_timings_ms=[],
                detached_launch_timings_ms=[],
                detached_launch_lock=threading.Lock(),
                event_append_trace={},
                event_append_trace_lock=threading.Lock(),
            )
            runtime.worker_artifacts.mkdir()
            try:
                keeper = sqlite3.connect(db_path)
                keeper.execute("PRAGMA journal_mode=WAL")
                keeper.execute("PRAGMA wal_autocheckpoint=0")
                keeper.execute("BEGIN")
                keeper.execute("SELECT COUNT(*) FROM schema_version").fetchone()
                replay_results, model_calls, production_jobs = _execute_plan(
                    chunk, runtime, 1
                )
                execution_completed = True
            finally:
                nested.shutdown(wait=True)
                sink.close()
                if not execution_completed and keeper is not None:
                    keeper.rollback()
                    keeper.close()
                    keeper = None
            audit = scan_campaign_privacy(segment_dir)
            case_oracles_passed = all(result.passed for result in replay_results)
            segment_passed = bool(
                audit["passed"]
                and case_oracles_passed
                and model_calls == 0
                and not production_jobs
            )
            event_counts = ledger.count_events()
            if keeper is not None:
                keeper.rollback()
                keeper.close()
                keeper = None

        replayed_cases += len(chunk)
        all_passed = all_passed and segment_passed
        for key in totals:
            totals[key] += int(audit.get(key) or 0)
        segments.append(
            {
                "segment": segment_index,
                "first_case_id": chunk[0].case_id,
                "last_case_id": chunk[-1].case_id,
                "cases": len(chunk),
                "events": int(event_counts["events_indexed"]),
                "case_oracles_passed": case_oracles_passed,
                "model_calls": model_calls,
                "privacy_passed": bool(audit["passed"]),
                "wal_shm_files_scanned": int(audit["wal_shm_files_scanned"]),
                "wal_shm_forbidden_hits": int(audit["wal_shm_forbidden_hits"]),
                "wal_shm_read_errors": int(audit["wal_shm_read_errors"]),
                "wal_shm_disappeared_files": int(
                    audit["wal_shm_disappeared_files"]
                ),
                "passed": segment_passed,
            }
        )
        if segment_passed:
            shutil.rmtree(segment_dir)

    summary = {
        "passed": bool(all_passed and replayed_cases == len(specs)),
        "source_cases": source_case_count,
        "support_cases": len(specs),
        "replayed_cases": replayed_cases,
        "chunk_cases": _WAL_FORENSIC_CHUNK_CASES,
        "segments": segments,
        **totals,
    }
    _write_json(campaign_dir / "wal_forensics.json", summary)
    return summary


def _render_report(metrics: dict[str, Any]) -> str:
    lines = [
        "# Memory Feature Offline Validation",
        "",
        f"- Status: **{str(metrics['status']).upper()}**",
        f"- Campaign type: `{metrics['campaign_type']}`",
        f"- Cases: {metrics['executed_cases']:,} executed / {metrics['requested_cases']:,} requested",
        f"- Central ledger events: {metrics['central_ledger']['events']:,}",
        f"- Duration: {metrics['duration_seconds']:.3f}s",
        "- Source read mode: `mode=ro&immutable=1`; source content rows read: `0`",
        "",
        "## Gates",
        "",
        "| Gate | Passed |",
        "|---|---:|",
    ]
    for name, passed in metrics["gates"].items():
        lines.append(f"| `{name}` | {str(bool(passed)).lower()} |")
    lines.extend(["", "Every failure row contains an independent single-case reproduction command.", ""])
    return "\n".join(lines)


def finalize_campaign_outputs(
    campaign_dir: Path,
    *,
    metrics: dict[str, Any],
    gates: dict[str, bool],
    case_failures: list[dict[str, Any]],
    privacy: dict[str, Any],
    repro_base: str,
    started: float,
) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Write the final bundle, then gate the bundle that actually exists.

    The duration and artifact-size limits are release properties of the whole
    campaign, including the final privacy scan and its status artifacts.  A
    pessimistic first release pass makes the candidate bundle at least as large
    as a passing bundle.  Subsequent passes stop only after the resource gates
    measured *after* all four final outputs were written agree with the gates in
    those outputs.  No file is written after the stable measurement.
    """
    campaign_dir = Path(campaign_dir)
    final_output_paths = (
        campaign_dir / "privacy_audit.json",
        campaign_dir / "offline_metrics.json",
        campaign_dir / "failures.jsonl",
        campaign_dir / "report.md",
    )
    campaign_type = str(metrics.get("campaign_type") or "smoke")
    current_gates = dict(gates)
    full_scan_passed = bool(privacy.get("passed"))
    full_scan_artifact_hits = int(privacy.get("artifact_forbidden_hits") or 0)
    if campaign_type == "release":
        # The first measured candidate includes both possible gate failures, so
        # a later passing bundle can only be smaller.
        current_gates["duration_under_30m"] = False
        current_gates["artifacts_under_3gb"] = False

    measured_once = False
    base_artifact_bytes: int | None = None
    recorded_duration_seconds: float | None = None
    for _pass in range(6):
        # Keep the state represented by this pass separate from measurements
        # taken after its files exist. Otherwise a late privacy failure can be
        # mistaken for an already-persisted gate value.
        written_gates = dict(current_gates)
        written_privacy_json = json.dumps(
            privacy,
            ensure_ascii=False,
            sort_keys=True,
            default=str,
        )
        written_artifact_bytes = int(metrics.get("artifact_bytes") or 0)
        passed = all(written_gates.values())
        status = f"{campaign_type}_{'passed' if passed else 'failed'}"
        failures = list(case_failures)
        failures.extend(
            {
                "case_id": f"gate:{name}",
                "category": "release_gate" if campaign_type == "release" else "smoke_gate",
                "error": "gate_failed",
                "repro_command": repro_base,
            }
            for name, value in written_gates.items()
            if not value
        )
        metrics.update(
            {
                "status": status,
                "privacy_passed": bool(privacy.get("passed")),
                "gates": dict(written_gates),
            }
        )
        _write_json(campaign_dir / "privacy_audit.json", privacy)
        _write_json(campaign_dir / "offline_metrics.json", metrics)
        (campaign_dir / "failures.jsonl").write_text(
            "".join(
                json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n"
                for row in failures
            ),
            encoding="utf-8",
        )
        (campaign_dir / "report.md").write_text(
            _render_report(metrics), encoding="utf-8"
        )

        # The expensive full DB/FTS/artifact scan ran before these four small
        # status files existed. Scan only that bounded delta on every rewrite;
        # re-reading the unchanged 1+ GiB ledger creates no extra assurance.
        status_privacy = scan_artifact_files_privacy(final_output_paths)
        privacy.update(
            {
                "artifact_forbidden_hits": (
                    full_scan_artifact_hits
                    + int(status_privacy["artifact_forbidden_hits"])
                ),
                "final_status_artifact_files_scanned": int(
                    status_privacy["artifact_files_scanned"]
                ),
                "final_status_artifact_read_errors": int(
                    status_privacy["artifact_read_errors"]
                ),
                "final_status_artifact_read_error_paths": list(
                    status_privacy["artifact_read_error_paths"]
                ),
                "passed": bool(full_scan_passed and status_privacy["passed"]),
            }
        )
        # This sample is deliberately after every final output above.  When the
        # gate values are already represented by that exact bundle, returning
        # without another write preserves the sample's validity.
        output_bytes = sum(path.stat().st_size for path in final_output_paths)
        if base_artifact_bytes is None:
            # One full traversal establishes the immutable bundle prefix. All
            # later writes are limited to final_output_paths, so their exact
            # sizes can be adjusted without another 40k-file stat walk.
            base_artifact_bytes = _artifact_bytes(campaign_dir) - output_bytes
        final_artifact_bytes = base_artifact_bytes + output_bytes
        final_duration = time.perf_counter() - started
        observed_duration_seconds = (
            math.ceil(max(0.0, final_duration) * 1000.0) / 1000.0
        )
        if recorded_duration_seconds is None:
            # Duration is not self-referential gate state. Record it after the
            # first complete final-output write/scan, then keep its serialized
            # width fixed while artifact_bytes and privacy reach their fixed
            # point. Re-sampling a rounded float on every pass can alternate
            # between values such as 1.1 and 1.111 and prevent convergence.
            recorded_duration_seconds = observed_duration_seconds
        elif campaign_type == "release" and (
            (recorded_duration_seconds <= _MAX_DURATION_SECONDS)
            != (final_duration <= _MAX_DURATION_SECONDS)
        ):
            # If stabilization itself crosses the hard boundary, advance the
            # persisted metric to the same conservative millisecond sample
            # that flips the gate. The report and gate must never disagree.
            recorded_duration_seconds = observed_duration_seconds
        measured_gates = dict(written_gates)
        measured_gates["privacy"] = bool(privacy["passed"])
        if campaign_type == "release":
            measured_gates["artifacts_under_3gb"] = (
                final_artifact_bytes <= _MAX_ARTIFACT_BYTES
            )
            measured_gates["duration_under_30m"] = (
                recorded_duration_seconds <= _MAX_DURATION_SECONDS
            )
        measured_privacy_json = json.dumps(
            privacy,
            ensure_ascii=False,
            sort_keys=True,
            default=str,
        )
        if (
            measured_once
            and measured_gates == written_gates
            and measured_privacy_json == written_privacy_json
            and written_artifact_bytes == final_artifact_bytes
        ):
            return metrics, failures

        metrics.update(
            {
                "artifact_bytes": final_artifact_bytes,
                "duration_seconds": recorded_duration_seconds,
            }
        )
        current_gates = measured_gates
        measured_once = True

    raise RuntimeError("final campaign resource gates did not stabilize")


def run_campaign(
    *,
    cases: int = DEFAULT_CASES,
    seed: int = DEFAULT_SEED,
    workers: int = DEFAULT_WORKERS,
    output_root: str | Path | None = None,
    source_db: str | Path | None = None,
    campaign_id: str | None = None,
    only_case: str | None = None,
) -> Path:
    cases = int(cases)
    workers = int(workers)
    if cases < 1 or workers < 1:
        raise ValueError("cases and workers must be positive")
    output_base = (
        Path(output_root or PROJECT_ROOT / ".agentloom" / "validation" / "memory_feature_validation")
        .expanduser()
        .resolve()
    )
    campaign_name = str(campaign_id or _default_campaign_id(seed)).strip()
    if not campaign_name or any(char in campaign_name for char in "/\\"):
        raise ValueError("campaign_id must be one path-safe component")
    campaign_dir = output_base / campaign_name
    campaign_dir.mkdir(parents=True, exist_ok=False)
    started_wall = datetime.now(UTC)
    started = time.perf_counter()
    source_stats = inspect_source_database(source_db)
    live_shape = _live_shape_replay(source_stats)
    release_shape = cases == DEFAULT_CASES and seed == DEFAULT_SEED and not only_case
    if release_shape:
        baseline_validation = run_fixed_point_comparison(
            campaign_dir,
            source_shape_sha256=_source_shape_sha256(live_shape),
            source_runs=int(live_shape["source_runs"]),
            source_events=int(live_shape["source_events"]),
            events_per_run=int(live_shape["events_per_run"]),
        )
    else:
        baseline_validation = {
            "valid": False,
            "reason": "fixed-point benchmark runs only for the exact 100k release corpus",
            "manifest": {},
            "performance": {},
            "current_performance": {},
        }
    plan = build_case_plan(cases, seed)
    if only_case:
        plan = [spec for spec in plan if spec.case_id == only_case]
        if not plan:
            raise ValueError(f"unknown deterministic case id: {only_case}")

    db_path = campaign_dir / "self_learning.db"
    worker_artifacts = campaign_dir / "worker_artifacts"
    worker_artifacts.mkdir()
    security_sink = SecurityArtifactSink(campaign_dir / "security_surfaces.jsonl")
    with _campaign_environment(campaign_dir):
        ledger = SelfLearningLedger(db_path)
        runtime = CampaignRuntime(
            ledger=ledger,
            memory_store=MemoryStore(db_path),
            queue=LearningJobQueue(db_path),
            nested_executor=ThreadPoolExecutor(max_workers=max(2, workers), thread_name_prefix="massval-nested"),
            security_sink=security_sink,
            worker_artifacts=worker_artifacts,
            events_per_run=int(live_shape["events_per_run"]),
            source_stats=source_stats,
            kick_call_timings_ms=[],
            detached_launch_timings_ms=[],
            detached_launch_lock=threading.Lock(),
            event_append_trace={},
            event_append_trace_lock=threading.Lock(),
        )
        security = [
            spec
            for spec in plan
            if spec.category == "redaction_digest_injection"
        ]
        try:
            results, model_calls, production_jobs = _execute_plan(
                plan, runtime, workers
            )
        finally:
            runtime.nested_executor.shutdown(wait=True)
            security_sink.close()
        postflight = _postflight_checks(runtime, plan, campaign_dir)
        forensic_privacy = _run_security_wal_forensics(
            security,
            campaign_dir=campaign_dir,
            source_stats=source_stats,
            events_per_run=int(live_shape["events_per_run"]),
        )
        central_wal_privacy = scan_wal_shm_privacy(campaign_dir)
        precheckpoint_privacy = {
            "passed": bool(
                forensic_privacy["passed"] and central_wal_privacy["passed"]
            ),
            "wal_shm_files_scanned": int(
                forensic_privacy["wal_shm_files_scanned"]
            )
            + int(central_wal_privacy["wal_shm_files_scanned"]),
            "wal_shm_forbidden_hits": int(
                forensic_privacy["wal_shm_forbidden_hits"]
            )
            + int(central_wal_privacy["wal_shm_forbidden_hits"]),
            "wal_shm_forbidden_findings": [
                *(
                    forensic_privacy.get(
                        "wal_shm_forbidden_findings"
                    )
                    or []
                ),
                *(
                    central_wal_privacy.get(
                        "wal_shm_forbidden_findings"
                    )
                    or []
                ),
            ],
            "wal_shm_read_errors": int(
                forensic_privacy.get("wal_shm_read_errors") or 0
            )
            + int(central_wal_privacy.get("wal_shm_read_errors") or 0),
            "wal_shm_disappeared_files": int(
                forensic_privacy.get("wal_shm_disappeared_files") or 0
            )
            + int(central_wal_privacy.get("wal_shm_disappeared_files") or 0),
            "wal_shm_read_error_paths": sorted(
                {
                    *(
                        forensic_privacy.get("wal_shm_read_error_paths") or []
                    ),
                    *(
                        central_wal_privacy.get("wal_shm_read_error_paths")
                        or []
                    ),
                }
            ),
        }
        checkpoint_conn = sqlite3.connect(db_path)
        try:
            checkpoint_conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
        finally:
            checkpoint_conn.close()
        event_counts = ledger.count_events()

    script = Path(__file__).resolve()
    source_arg = f" --source-db {shlex.quote(str(Path(source_db).resolve()))}" if source_db else ""
    repro_base = (
        f"{shlex.quote(sys.executable)} {shlex.quote(str(script))} --cases {cases} --seed {seed} --workers {workers}"
        f"{source_arg} --output-root {shlex.quote(str(output_base))} --campaign-id repro-{campaign_name}"
    )
    repro_prefix = f"{repro_base} --only-case"
    _write_manifest(campaign_dir / "manifest.jsonl.gz", results, repro_prefix)
    environment = {
        "campaign_id": campaign_name,
        "python": sys.version.split()[0],
        "platform": platform.platform(),
        "cpu_count": os.cpu_count(),
        "started_at": started_wall.isoformat(),
        "arguments": {
            "cases": cases,
            "seed": seed,
            "workers": workers,
            "only_case": only_case or "",
            "fixed_point_reference_commit": DEFAULT_BASELINE_COMMIT,
            "wal_forensic_chunk_cases": _WAL_FORENSIC_CHUNK_CASES,
        },
        "oracle_source": "independent_seeded_oracle_v2",
        "live_shape_replay": live_shape,
        "source_database": source_stats,
    }
    _write_json(campaign_dir / "environment.json", environment)
    repro_path = campaign_dir / "repro.sh"
    repro_path.write_text(
        "\n".join(
            [
                "#!/usr/bin/env bash",
                "set -euo pipefail",
                ': "${CASE_ID:?set CASE_ID}"',
                f'{repro_prefix} "$CASE_ID"',
                "",
            ]
        ),
        encoding="utf-8",
    )
    repro_path.chmod(0o755)

    privacy = scan_campaign_privacy(campaign_dir)
    privacy["wal_shm_files_scanned"] = int(precheckpoint_privacy.get("wal_shm_files_scanned") or 0)
    privacy["wal_shm_forbidden_hits"] = int(precheckpoint_privacy.get("wal_shm_forbidden_hits") or 0)
    privacy["wal_shm_forbidden_findings"] = list(
        precheckpoint_privacy.get("wal_shm_forbidden_findings") or []
    )
    privacy["wal_shm_read_errors"] = int(
        precheckpoint_privacy.get("wal_shm_read_errors") or 0
    )
    privacy["wal_shm_disappeared_files"] = int(
        precheckpoint_privacy.get("wal_shm_disappeared_files") or 0
    )
    privacy["wal_shm_read_error_paths"] = list(
        precheckpoint_privacy.get("wal_shm_read_error_paths") or []
    )
    privacy["passed"] = bool(
        privacy["passed"]
        and precheckpoint_privacy.get("passed")
        and privacy["wal_shm_forbidden_hits"] == 0
        and privacy["wal_shm_read_errors"] == 0
    )
    privacy.update(
        {
            "source_open_mode": "mode=ro&immutable=1",
            "source_content_rows_read": 0,
            "source_text_copied": False,
            "forensic_wal_replay": forensic_privacy,
        }
    )
    _write_json(campaign_dir / "privacy_audit.json", privacy)

    coverage = _coverage(
        results,
        postflight,
        model_calls,
        production_jobs,
        runtime.kick_call_timings_ms,
        runtime.detached_launch_timings_ms,
    )
    append_latencies = [float(result.observed.get("append_ms", 0.0)) for result in results]
    rss_mb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / (1024 * 1024 if sys.platform == "darwin" else 1024)
    current_performance = {
        "ledger_append_p95_ms": round(_nearest_percentile(append_latencies, 0.95), 3),
        "fts_query_p95_ms": float(coverage["fts_search"]["p95_ms"]),
        "bytes_per_event": round(db_path.stat().st_size / max(1, int(event_counts["events_indexed"])), 3),
    }
    eligibility = release_eligibility(
        cases,
        seed,
        only_case,
        fixed_point_valid=bool(baseline_validation["valid"]),
    )
    regression = _regression_gate(
        baseline_validation.get("current_performance") or {},
        baseline_validation.get("performance") or {},
        paired_analysis=baseline_validation.get("paired_analysis") or {},
    )
    executed_by_category = {
        category: sum(result.category == category for result in results) for category in CATEGORY_WEIGHTS
    }
    corpus_contract = release_corpus_contract(
        cases,
        executed_by_category,
        source_runs=int(live_shape["source_runs"]),
        source_events=int(live_shape["source_events"]),
    )
    common_gates = {
        "all_case_oracles": all(result.passed for result in results),
        "privacy": bool(privacy["passed"]),
        "sqlite_integrity": bool(postflight["sqlite_integrity"]),
        "schema_and_migration": bool(postflight["schema_v4"] and postflight["migration_v4"]),
        "job_terminal_state": bool(postflight["job_terminal_state"] and postflight["worker_lease_released"]),
        "exact_evidence_accuracy": coverage["exact_evidence"]["accuracy"] == 1.0,
        "revision_accuracy": coverage["revision_paths"]["accuracy"] == 1.0,
        "fts_unique_marker_accuracy": coverage["fts_search"]["accuracy"] == 1.0,
        "scroll_accuracy": coverage["fts_scroll"]["accuracy"] == 1.0,
        "redaction_recall": coverage["redaction_injection"]["recall"] == 1.0,
        "redaction_false_positive_rate": coverage["redaction_injection"]["false_positive_rate"] <= 0.001,
        "session_end_no_model": coverage["session_end"]["model_calls"] == 0,
        "session_end_real_kick_path": (
            coverage["session_end"]["kick_calls"] == coverage["session_end"]["expected_kick_calls"]
        ),
        "session_end_detached_launch": (
            coverage["session_end"]["checked"] == 0 or coverage["session_end"]["detached_launch_checked"] == 1
        ),
        "root_persistence": (
            coverage["root_persistence"]["accuracy"] == 1.0
            and coverage["root_persistence"]["repeated_finalize_cas_accuracy"] == 1.0
        ),
        "production_job_contracts": (
            coverage["session_end"]["checked"] == 0
            or all(
                bool(coverage["production_jobs"].get(key))
                for key in (
                    "initial_jobs_terminal",
                    "normal_review_audits",
                    "forged_proposals_absent",
                    "frozen_digest_reused",
                    "proposal_evidence_filtered",
                    "review_audit_idempotent",
                    "crash_recovery_succeeded",
                    "fallback_digest_reused",
                    "fallback_succeeded",
                    "retention_crash_recovered",
                    "curator_validation_route",
                    "detached_central_job_terminal",
                    "detached_observed_before_in_process_drain",
                    "detached_proof_db_isolated",
                    "detached_proof_kick_used_explicit_db_path",
                    "root_review_jobs_attributed",
                )
            )
        ),
        # A single-case command is a reproducer, not a seven-route coverage
        # campaign.  Its route is already asserted by that case's oracle.
        "security_route_contracts": bool(only_case) or all(coverage["security_routes"].values()),
        "outbox_worker_accuracy": coverage["outbox_worker"]["accuracy"] == 1.0,
    }
    release_gates = {
        "release_eligible": bool(eligibility["eligible"]),
        "requested_exactly_100k": corpus_contract["requested_exactly_100k"],
        "executed_exactly_100k": corpus_contract["executed_exactly_100k"],
        "category_quotas_exact": corpus_contract["category_quotas_exact"],
        "source_shape_82_runs_1706_events": corpus_contract["source_shape_82_runs_1706_events"],
        "central_event_count": int(event_counts["events_indexed"]) >= DEFAULT_CASES,
        "fts_query_p95": coverage["fts_search"]["p95_ms"] <= 250.0,
        "ranking_top1": coverage["ranking"]["top1_accuracy"] >= 0.995,
        "session_end_p95": coverage["session_end"]["p95_ms"] < 100.0,
        "session_end_p99": coverage["session_end"]["p99_ms"] < 250.0,
        "detached_launch_latency": coverage["session_end"]["detached_launch_p95_ms"] < 250.0,
        "relative_regression": bool(regression["passed"]),
        "rss_under_2gb": rss_mb <= _MAX_RSS_MB,
    }
    provisional_metrics: dict[str, Any] = {
        "status": "smoke_failed",
        "campaign_type": "release"
        if eligibility["fixed_case_count"] and eligibility["fixed_seed"] and eligibility["full_campaign"]
        else "smoke",
        "release_eligible": bool(eligibility["eligible"]),
        "release_eligibility": eligibility,
        "release_corpus_contract": corpus_contract,
        "requested_cases": cases,
        "executed_cases": len(results),
        "passed_cases": sum(result.passed for result in results),
        "failed_cases": sum(not result.passed for result in results),
        "seed": seed,
        "workers": workers,
        "category_quotas": allocate_quotas(cases),
        "categories": {
            category: {
                "planned": allocate_quotas(cases)[category],
                "executed": executed_by_category[category],
                "passed": sum(result.category == category and result.passed for result in results),
                "failed": sum(result.category == category and not result.passed for result in results),
            }
            for category in CATEGORY_WEIGHTS
        },
        "central_ledger": {
            "path": str(db_path),
            "runs": event_counts["runs_indexed"],
            "events": event_counts["events_indexed"],
        },
        "payload_bytes": {
            "p50": int(_nearest_percentile([result.payload_bytes for result in results], 0.50)),
            "p95": int(_nearest_percentile([result.payload_bytes for result in results], 0.95)),
            "p99": int(_nearest_percentile([result.payload_bytes for result in results], 0.99)),
            "max": max((result.payload_bytes for result in results), default=0),
        },
        "coverage": coverage,
        "postflight": postflight,
        "privacy_passed": bool(privacy["passed"]),
        "performance": current_performance,
        "regression": regression,
        "baseline_validation": baseline_validation,
        "max_rss_mb": round(rss_mb, 2),
        "duration_seconds": round(time.perf_counter() - started, 3),
        "artifact_bytes": 0,
        "gates": {},
    }
    _write_json(campaign_dir / "offline_metrics.json", provisional_metrics)
    (campaign_dir / "report.md").write_text(
        _render_report({**provisional_metrics, "gates": common_gates}), encoding="utf-8"
    )
    gates = {**common_gates, **(release_gates if provisional_metrics["campaign_type"] == "release" else {})}
    passed = all(gates.values())
    status = ("release_" if provisional_metrics["campaign_type"] == "release" else "smoke_") + (
        "passed" if passed else "failed"
    )
    failures = [
        {
            "case_id": result.case_id,
            "category": result.category,
            "error": result.error or "independent_oracle_mismatch",
            "repro_command": f"{repro_prefix} {shlex.quote(result.case_id)}",
        }
        for result in results
        if not result.passed
    ]
    metrics = {
        **provisional_metrics,
        "status": status,
        "duration_seconds": round(time.perf_counter() - started, 3),
        "artifact_bytes": 0,
        "gates": gates,
    }
    _write_json(campaign_dir / "offline_metrics.json", metrics)
    (campaign_dir / "failures.jsonl").write_text(
        "".join(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n" for row in failures), encoding="utf-8"
    )
    (campaign_dir / "report.md").write_text(_render_report(metrics), encoding="utf-8")

    # The full scan above covers every immutable campaign artifact. The final
    # writer audits its four mutable status files after each rewrite.
    gates["privacy"] = bool(privacy["passed"])
    finalize_campaign_outputs(
        campaign_dir,
        metrics=metrics,
        gates=gates,
        case_failures=failures,
        privacy=privacy,
        repro_base=repro_base,
        started=started,
    )
    return campaign_dir


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cases", type=int, default=DEFAULT_CASES)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--workers", type=int, default=DEFAULT_WORKERS)
    parser.add_argument(
        "--output-root", type=Path, default=PROJECT_ROOT / ".agentloom" / "validation" / "memory_feature_validation"
    )
    parser.add_argument("--source-db", type=Path, default=PROJECT_ROOT / ".agentloom" / "self_learning.db")
    parser.add_argument("--campaign-id", default=None)
    parser.add_argument("--only-case", default=None)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    campaign_dir = run_campaign(
        cases=args.cases,
        seed=args.seed,
        workers=args.workers,
        output_root=args.output_root,
        source_db=args.source_db,
        campaign_id=args.campaign_id,
        only_case=args.only_case,
    )
    metrics = json.loads((campaign_dir / "offline_metrics.json").read_text(encoding="utf-8"))
    print(json.dumps({"campaign_dir": str(campaign_dir), "status": metrics["status"]}, ensure_ascii=False))
    return 0 if str(metrics["status"]).endswith("_passed") else 1


